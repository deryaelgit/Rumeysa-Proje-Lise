const { chromium, expect } = require('@playwright/test');
const fs=require('node:fs/promises');
const path=require('node:path');
const os=require('node:os');
(async()=>{
  const dir=await fs.mkdtemp(path.join(os.tmpdir(),'edebiyat-browser-'));
  process.env.SUGGESTIONS_FILE=path.join(dir,'oneriler.json');
  const {createServer}=require('../tools/server.cjs');
  const server=createServer();
  await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
  const base=`http://127.0.0.1:${server.address().port}`;
  let browser;
  try{
    browser=await chromium.launch({headless:true});
    const page=await browser.newPage({viewport:{width:1440,height:1100}});
    const errors=[];page.on('pageerror',error=>errors.push(error.message));
    await page.route('https://tile.openstreetmap.org/**',route=>route.abort());
    await page.goto(base,{waitUntil:'networkidle'});
    await expect(page.locator('.place-card')).toHaveCount(10);
    await expect(page.locator('.map-marker')).toHaveCount(10);
    await expect(page.locator('.map-marker.tahmini')).toHaveCount(8);
    await page.locator('.leaflet-marker-icon').first().hover();
    await expect(page.locator('.photo-tooltip .popup-foto')).toBeVisible();
    await page.mouse.move(0,0);
    await page.click('[data-map-style="uydu"]');
    await expect(page.locator('[data-map-style="uydu"]')).toHaveAttribute('aria-pressed','true');
    await page.click('#binaDetay');
    await page.click('[data-map-style="atlas"]');
    await page.click('[data-map-style="sokak"]');
    await page.selectOption('#kitapSecim','Fatih-Harbiye');
    await expect(page.locator('.place-card')).toHaveCount(2);
    await expect(page.locator('.leaflet-overlay-pane path')).toHaveCount(1);
    await page.uncheck('#rotaCheck');
    await expect(page.locator('.leaflet-overlay-pane path')).toHaveCount(0);
    await page.click('#rastgeleBtn');
    await expect(page.locator('#mekanDialog')).toBeVisible();
    await expect(page.locator('#mekanDialog')).toContainText('Eskiden / Bugün');
    await expect(page.locator('#mekanDialog .detail-maps')).toHaveCount(1);
    await page.keyboard.press('Escape');
    await page.click('#sifirlaBtn');
    await page.fill('#aramaKutusu','nisantasi');
    await expect(page.locator('.place-card')).toHaveCount(1);
    await page.fill('#aramaKutusu','bulunmayacak-xyz');
    await expect(page.locator('.empty-state')).toBeVisible();
    await expect(page.locator('#rastgeleBtn')).toBeDisabled();
    await page.click('#sifirlaBtn');
    await page.evaluate(() => mekanlar.push({...mekanlar[0], id:'ayni-mekan-test', kitap:'Aynı mekânda ikinci kitap', yazar:'İkinci yazar', ozet:'İkinci eserin mekân anlatımı'}));
    await page.locator('.place-card').first().click();
    await expect(page.locator('#mekanDialog .literary-record')).toHaveCount(2);
    await expect(page.locator('#mekanDialog')).toContainText('Aynı mekânda ikinci kitap');
    await expect(page.locator('#mekanDialog')).toContainText('İkinci eserin mekân anlatımı');
    await page.keyboard.press('Escape');
    await page.evaluate(() => mekanlar.pop());
    await page.click('#oneriAc');
    for(const [field,value] of Object.entries({kitap:'Tarayıcı test kitabı',yazar:'Test yazarı',mekan:'Test mekânı',not:'Kalıcı dosya test kaydı'}))await page.locator(`[name="${field}"]`).fill(value);
    await page.click('#oneriForm [type=submit]');
    await expect(page.locator('#oneriDurum')).toContainText('oneriler.json dosyasına kaydedildi');
    const records=JSON.parse(await fs.readFile(process.env.SUGGESTIONS_FILE,'utf8'));
    if(records.length!==1)throw Error('Dosyaya kayıt bulunamadı');
    await page.keyboard.press('Escape');
    await page.click('#kaynakcaBtn');
    await expect(page.locator('#kaynakcaListesi article')).toHaveCount(8);
    await page.keyboard.press('Escape');
    await fs.mkdir('test-results',{recursive:true});
    await page.screenshot({path:'test-results/desktop.png',fullPage:true});
    await page.setViewportSize({width:390,height:844});
    await expect(page.locator('.place-card')).toHaveCount(10);
    if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw Error('Mobil yatay taşma');
    await page.screenshot({path:'test-results/mobile.png',fullPage:true});
    await page.goto(base+'/stand.html');
    await expect(page.locator('#qrKod svg')).toHaveCount(1);
    await page.fill('#siteUrl','https://deryaelgit.github.io/Rumeysa-Proje-Lise/');
    await page.click('#qrForm [type=submit]');
    await expect(page.locator('#qrDurum')).toContainText('QR kod hazır');
    if(errors.length)throw Error(errors.join('\n'));
    console.log('Tarayıcı kontrolü başarılı: işaretçiler, rota, filtreler, ayrıntı, JSON kaydı, kaynakça, mobil, QR.');
  }finally{await browser?.close();await new Promise(resolve=>server.close(resolve));await fs.rm(dir,{recursive:true,force:true});}
})().catch(error=>{console.error(error);process.exitCode=1;});
